def engineer_features(df):
    """Feature engineering yang lebih komprehensif"""
    required = {
        "household_id", "year", "month", "days_in_month",
        "bill_amount", "estimated_kwh", "total_duration_hours",
        "total_power_watt", "active_device_count"
    }
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Kolom training_data.csv kurang: {sorted(missing)}")

    data = df.copy()
    data = data.sort_values(["household_id", "year", "month"])

    group = data.groupby("household_id")["bill_amount"]
    group_kwh = data.groupby("household_id")["estimated_kwh"]

    # Lag features (4 lag untuk capture pola lebih panjang)
    for lag in [1, 2, 3, 4]:
        data[f"bill_lag_{lag}"] = group.shift(lag)
        data[f"estimated_kwh_lag_{lag}"] = group_kwh.shift(lag)

    # Rolling statistics
    data["bill_rolling_avg_3"] = group.transform(
        lambda x: x.shift(1).rolling(window=3).mean()
    )
    data["bill_rolling_avg_6"] = group.transform(
        lambda x: x.shift(1).rolling(window=6).mean()
    )
    data["bill_rolling_std_3"] = group.transform(
        lambda x: x.shift(1).rolling(window=3).std()
    )

    # Month-over-month change
    data["bill_mom_change"] = data.groupby("household_id")["bill_amount"].pct_change() * 100

    # Fitur siklik untuk bulan (encoding circular)
    data["month_sin"] = np.sin(2 * np.pi * data["month"] / 12)
    data["month_cos"] = np.cos(2 * np.pi * data["month"] / 12)
    data["quarter"] = data["month"].apply(lambda x: (x-1)//3 + 1)

    # Holiday season (Desember + Januari)
    data["is_holiday_season"] = data["month"].isin([12, 1]).astype(int)

    # Ramadan effect approximation (bulan 3-4)
    data["is_ramadan_effect"] = data["month"].isin([3, 4]).astype(int)

    # Efisiensi pemakaian (kWh per device per jam)
    data["avg_daily_kwh"] = data["estimated_kwh"] / data["days_in_month"]
    data["efficiency_score"] = data["estimated_kwh"] / (data["total_power_watt"] * data["total_duration_hours"] / 1000)
    data["efficiency_score"] = data["efficiency_score"].fillna(1).clip(0.5, 2)

    # Target
    data["next_month_bill"] = group.shift(-1)

    # Drop baris dengan nilai NaN
    required_features = FEATURE_COLUMNS + ["next_month_bill"]
    data_clean = data.dropna(subset=required_features)

    print(f"Feature engineering selesai: {len(data_clean)} baris tersisa")
    return data_clean

