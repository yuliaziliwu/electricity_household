# ============================================
def train_model_enhanced(data, model_type="xgboost"):
    """Training dengan multiple model options dan tuning"""
    if data.empty:
        raise ValueError("Data training kosong setelah feature engineering")

    X = data[FEATURE_COLUMNS]
    y = data["next_month_bill"]

    # Standardisasi untuk model yang sensitif
    scaler = RobustScaler()
    X_scaled = scaler.fit_transform(X)

    # Split dengan mempertahankan urutan waktu
    train_size = int(0.8 * len(X))
    X_train, X_test = X_scaled[:train_size], X_scaled[train_size:]
    y_train, y_test = y.iloc[:train_size], y.iloc[train_size:]

    print(f"Training size: {len(X_train)}, Test size: {len(X_test)}")

    # Pilih model
    if model_type == "xgboost":
        model = XGBRegressor(
            n_estimators=500,
            max_depth=8,
            learning_rate=0.05,
            subsample=0.8,
            colsample_bytree=0.8,
            random_state=RANDOM_STATE,
            n_jobs=-1
        )
    elif model_type == "lightgbm":
        model = LGBMRegressor(
            n_estimators=500,
            max_depth=8,
            learning_rate=0.05,
            subsample=0.8,
            colsample_bytree=0.8,
            random_state=RANDOM_STATE,
            n_jobs=-1,
            verbose=-1
        )
    elif model_type == "randomforest":
        model = RandomForestRegressor(
            n_estimators=500,
            max_depth=12,
            min_samples_leaf=4,
            random_state=RANDOM_STATE,
            n_jobs=-1
        )
    else:
        model = GradientBoostingRegressor(
            n_estimators=200,
            max_depth=6,
            learning_rate=0.05,
            random_state=RANDOM_STATE
        )

    model.fit(X_train, y_train)

    # Predictions
    predictions = model.predict(X_test)

    # Metrics
    mae = mean_absolute_error(y_test, predictions)
    rmse = np.sqrt(mean_squared_error(y_test, predictions))
    r2 = r2_score(y_test, predictions)

    # Mean Absolute Percentage Error (lebih intuitif)
    mape = np.mean(np.abs((y_test - predictions) / y_test)) * 100

    metrics = {
        "mae": float(mae),
        "rmse": float(rmse),
        "r2": float(r2),
        "mape": float(mape),
        "accuracy_percent": float(max(0, 100 - mape))
    }

    return model, scaler, metrics, X_test, y_test, predictions


def hyperparameter_tuning(data):
    """Grid search untuk menemukan hyperparameter terbaik"""
    print("\n=== HYPERPARAMETER TUNING ===")

    X = data[FEATURE_COLUMNS]
    y = data["next_month_bill"]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=RANDOM_STATE
    )

    # Parameter grid untuk XGBoost
    param_grid = {
        'n_estimators': [300, 500],
        'max_depth': [6, 8, 10],
        'learning_rate': [0.03, 0.05, 0.07],
        'subsample': [0.7, 0.8, 0.9]
    }

    xgb = XGBRegressor(random_state=RANDOM_STATE, n_jobs=-1)

    grid_search = GridSearchCV(
        xgb, param_grid, cv=3,
        scoring='neg_mean_absolute_error',
        n_jobs=-1, verbose=0
    )
    grid_search.fit(X_train, y_train)

    print(f"Best parameters: {grid_search.best_params_}")
    print(f"Best MAE: {-grid_search.best_score_:.2f}")

    return grid_search.best_estimator_

