def calculate_estimated_kwh(power_watt, duration_hours, days):
    return power_watt * duration_hours * days / 1000


def get_seasonal_factor(month, year):
    """Faktor musiman yang lebih realistis untuk listrik di Indonesia"""
    dry_season = month in [4, 5, 6, 7, 8, 9]
    peak_dry = month in [7, 8]

    if peak_dry:
        base_factor = 1.15
    elif dry_season:
        base_factor = 1.05
    else:
        base_factor = 0.95

    ramadan_factor = 1.18 if month in [3, 4] else 1.0
    holiday_factor = 1.12 if month == 12 else 1.0

    return base_factor * ramadan_factor * holiday_factor


def create_realistic_training_data(path=DATA_PATH, households=200, months=36):
    """Membuat data training yang lebih realistis"""
    rng = np.random.default_rng(RANDOM_STATE)
    rows = []

    for household_id in range(1, households + 1):
        household_type = rng.choice(["small", "medium", "large"], p=[0.3, 0.5, 0.2])

        if household_type == "small":
            base_bill = rng.uniform(150_000, 300_000)
            device_range = (3, 10)
            power_range = (60, 150)
            tariff_per_kwh = rng.uniform(1350, 1500)
        elif household_type == "medium":
            base_bill = rng.uniform(300_000, 600_000)
            device_range = (8, 18)
            power_range = (100, 220)
            tariff_per_kwh = rng.uniform(1400, 1550)
        else:
            base_bill = rng.uniform(600_000, 1_200_000)
            device_range = (15, 30)
            power_range = (150, 350)
            tariff_per_kwh = rng.uniform(1450, 1650)

        usage_growth_trend = rng.uniform(0.03, 0.08)
        previous_bill = base_bill

        for idx in range(months):
            year = 2022 + idx // 12
            month = (idx % 12) + 1
            days = calendar.monthrange(year, month)[1]

            growth_factor = 1 + (idx / 12) * usage_growth_trend

            if 9 <= month <= 17:
                device_mult = 0.8
            elif 18 <= month <= 22:
                device_mult = 1.3
            else:
                device_mult = 0.6

            active_device_count = int(rng.integers(device_range[0], device_range[1]) * device_mult)
            avg_power = rng.uniform(power_range[0], power_range[1])
            total_power_watt = active_device_count * avg_power

            is_weekend = (idx % 7) in [5, 6]
            if is_weekend:
                total_duration_hours = rng.uniform(6, 14)
            else:
                total_duration_hours = rng.uniform(4, 10)

            estimated_kwh = calculate_estimated_kwh(
                total_power_watt, total_duration_hours, days
            ) * growth_factor

            seasonal_factor = get_seasonal_factor(month, year)
            tariff = tariff_per_kwh * (1 + rng.normal(0, 0.03))
            device_bill = estimated_kwh * tariff
            inertia_weight = rng.uniform(0.4, 0.7)
            noise_std = max(15_000, device_bill * 0.05)
            noise = rng.normal(0, noise_std)

            bill_amount = (inertia_weight * previous_bill +
                          (1 - inertia_weight) * device_bill * seasonal_factor +
                          noise)
            bill_amount = max(50_000, bill_amount)

            rows.append({
                "household_id": household_id,
                "year": year,
                "month": month,
                "days_in_month": days,
                "bill_amount": round(bill_amount, 2),
                "estimated_kwh": round(estimated_kwh, 3),
                "total_duration_hours": round(total_duration_hours, 2),
                "total_power_watt": round(total_power_watt, 2),
                "active_device_count": active_device_count,
                "household_type": household_type,
                "tariff_per_kwh": round(tariff, 2),
            })

            previous_bill = bill_amount

    df = pd.DataFrame(rows)
    df.to_csv(path, index=False)
    print(f"Dataset dengan {len(df)} baris berhasil dibuat di {path}")
    return df


def load_training_data(path=DATA_PATH):
    if not os.path.exists(path):
        print(f"{path} tidak ditemukan. Membuat dataset realistis...")
        return create_realistic_training_data(path)
    return pd.read_csv(path)

