def predict_next_bill_rf(input_data, model_path=MODEL_PATH):
    """Prediksi dengan Random Forest dan confidence interval SEMPIT"""
    artifact = joblib.load(model_path)
    model = artifact["model"]
    scaler = artifact["scaler"]
    feature_columns = artifact["feature_columns"]
    metrics = artifact["metadata"]["metrics"]

    # Konversi input ke DataFrame
    if isinstance(input_data, dict):
        df = pd.DataFrame([input_data])
    else:
        df = input_data.copy()

    # Feature engineering untuk input
    if "estimated_kwh" not in df.columns:
        days = df["days"] if "days" in df.columns else 30
        df["estimated_kwh"] = calculate_estimated_kwh(
            df.get("total_power_watt", 1000),
            df.get("total_duration_hours", 6),
            days
        )

    if "bill_rolling_avg_3" not in df.columns and "bill_lag_1" in df.columns:
        df["bill_rolling_avg_3"] = df[["bill_lag_1", "bill_lag_2", "bill_lag_3"]].mean(axis=1)
        df["bill_rolling_avg_6"] = df[[f"bill_lag_{i}" for i in range(1, 7) if f"bill_lag_{i}" in df.columns]].mean(axis=1)

    if "month" in df.columns:
        df["month_sin"] = np.sin(2 * np.pi * df["month"] / 12)
        df["month_cos"] = np.cos(2 * np.pi * df["month"] / 12)

    # Cek missing columns
    missing = [col for col in feature_columns if col not in df.columns]
    if missing:
        for col in missing:
            if col.startswith("bill_lag"):
                df[col] = df.get("bill_amount", 300000)
            elif col == "bill_rolling_avg_3":
                df[col] = df.get("bill_amount", 300000)
            elif col == "bill_mom_change":
                df[col] = 0
            elif col == "quarter":
                df[col] = (df.get("month", 6) - 1) // 3 + 1
            else:
                df[col] = 0

    X = df[feature_columns].astype(float)
    X_scaled = scaler.transform(X)

    # Prediksi dengan Random Forest
    predictions = model.predict(X_scaled)

    # Estimasi standard deviation dari individual trees (untuk range kecil)
    if hasattr(model, 'estimators_'):
        all_preds = np.column_stack([tree.predict(X_scaled) for tree in model.estimators_[:50]])
        std_predictions = np.std(all_preds, axis=1)
    else:
        std_predictions = predictions * 0.02  # fallback yang sangat kecil

    # ========== RANGE YANG SANGAT KECIL ==========
    mape = metrics['mape']

    # Faktor pengali untuk standard deviation (semakin kecil, semakin sempit range)
    std_factor = 0.65  # 0.65 = range sekitar 2x lebih kecil dari std

    # Batas maksimal persentase margin
    max_margin_percent = 6  # Maksimal 6% margin

    if len(predictions) == 1:
        pred_value = float(max(predictions[0], 0))
        std_value = float(std_predictions[0])

        # Margin berdasarkan standard deviation yang diperkecil
        margin = std_value * std_factor

        # Jangan melebihi batas maksimal
        max_margin = pred_value * (max_margin_percent / 100)
        final_margin = min(margin, max_margin)
        final_margin_percent = (final_margin / pred_value) * 100

        # Khusus untuk prediksi yang sangat stabil, beri margin minimal 1%
        if final_margin_percent < 1.0:
            final_margin = pred_value * 0.01
            final_margin_percent = 1.0

        return {
            "predicted_next_month_bill": round(pred_value, 2),
            "confidence_lower": round(float(max(pred_value - final_margin, 0)), 2),
            "confidence_upper": round(float(pred_value + final_margin), 2),
            "margin_percent": round(final_margin_percent, 2),
            "prediction_std": round(std_value, 2),
            "mape_model": round(mape, 2)
        }

    return [
        {
            "predicted_next_month_bill": round(float(max(pred_val, 0)), 2),
            "confidence_lower": round(float(max(pred_val - (std_val * std_factor), 0)), 2),
            "confidence_upper": round(float(pred_val + (std_val * std_factor)), 2),
            "margin_percent": round(((std_val * std_factor) / pred_val) * 100, 2)
        }
        for pred_val, std_val in zip(predictions, std_predictions)
    ]


def save_model_rf(model, scaler, metrics, feature_importances=None, path=MODEL_PATH):
    artifact = {
        "model": model,
        "scaler": scaler,
        "feature_columns": FEATURE_COLUMNS,
        "metadata": {
            "target": "next_month_bill",
            "currency": "IDR",
            "metrics": metrics,
            "feature_importances": feature_importances,
            "version": "2.0-random-forest",
            "model_type": "random_forest"
        },
    }
    joblib.dump(artifact, path)
    print(f"Random Forest model saved to {path}")
    return artifact

