# RANDOM FOREST MODEL (TANPA ENSEMBLE)
# ============================================
def train_random_forest_model(data):
    """Training dengan Random Forest Regressor saja"""
    if data.empty:
        raise ValueError("Data training kosong setelah feature engineering")

    X = data[FEATURE_COLUMNS]
    y = data["next_month_bill"]

    # Standardisasi
    scaler = RobustScaler()
    X_scaled = scaler.fit_transform(X)

    # Split data (time-based)
    train_size = int(0.8 * len(X))
    X_train, X_test = X_scaled[:train_size], X_scaled[train_size:]
    y_train, y_test = y.iloc[:train_size], y.iloc[train_size:]

    print(f"Training size: {len(X_train)}, Test size: {len(X_test)}")

    # Random Forest dengan hyperparameter yang dioptimasi untuk prediksi stabil
    rf_model = RandomForestRegressor(
        n_estimators=500,
        max_depth=12,
        min_samples_split=5,
        min_samples_leaf=3,
        max_features='sqrt',
        random_state=RANDOM_STATE,
        n_jobs=-1
    )

    rf_model.fit(X_train, y_train)

    # Prediksi
    predictions = rf_model.predict(X_test)

    # Metrics
    mae = mean_absolute_error(y_test, predictions)
    rmse = np.sqrt(mean_squared_error(y_test, predictions))
    r2 = r2_score(y_test, predictions)
    mape = np.mean(np.abs((y_test - predictions) / y_test)) * 100

    # Hitung prediction interval dari quantile predictions (untuk range kecil)
    # Menggunakan 10 trees untuk estimasi interval yang lebih sempit
    all_predictions = np.column_stack([
        tree.predict(X_test) for tree in rf_model.estimators_[:50]  # ambil 50 trees untuk estimasi varian
    ])

    std_predictions = np.std(all_predictions, axis=1)

    metrics = {
        "mae": float(mae),
        "rmse": float(rmse),
        "r2": float(r2),
        "mape": float(mape),
        "accuracy_percent": float(max(0, 100 - mape)),
    }

    print(f"\n=== RANDOM FOREST PERFORMANCE ===")
    print(f"MAE: {mae:,.2f} IDR")
    print(f"RMSE: {rmse:,.2f} IDR")
    print(f"R²: {r2:.4f}")
    print(f"MAPE: {mape:.2f}%")
    print(f"Accuracy: {100-mape:.2f}%")

    return rf_model, scaler, metrics, X_test, y_test, predictions, std_predictions


