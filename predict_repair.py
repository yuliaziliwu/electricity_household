def plot_results(y_test, predictions, metrics, std_predictions=None):
    """Visualisasi hasil prediksi"""
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))

    # Plot 1: Actual vs Predicted
    ax1 = axes[0, 0]
    ax1.scatter(y_test, predictions, alpha=0.5, edgecolors='k', linewidth=0.5)
    ax1.plot([y_test.min(), y_test.max()], [y_test.min(), y_test.max()], 'r--', lw=2)
    ax1.set_xlabel("Actual Bill (IDR)")
    ax1.set_ylabel("Predicted Bill (IDR)")
    ax1.set_title(f"Actual vs Predicted (R² = {metrics['r2']:.3f})")

    # Plot 2: Residuals
    ax2 = axes[0, 1]
    residuals = y_test - predictions
    ax2.scatter(predictions, residuals, alpha=0.5, edgecolors='k', linewidth=0.5)
    ax2.axhline(y=0, color='r', linestyle='--')
    ax2.set_xlabel("Predicted Bill (IDR)")
    ax2.set_ylabel("Residuals (IDR)")
    ax2.set_title(f"Residual Plot (MAE = {metrics['mae']:.0f})")

    # Plot 3: Distribution of errors
    ax3 = axes[1, 0]
    ax3.hist(residuals, bins=50, edgecolor='black', alpha=0.7)
    ax3.axvline(x=0, color='r', linestyle='--')
    ax3.set_xlabel("Prediction Error (IDR)")
    ax3.set_ylabel("Frequency")
    ax3.set_title("Distribution of Prediction Errors")

    # Plot 4: Percentage error
    ax4 = axes[1, 1]
    pct_errors = (residuals / y_test) * 100
    pct_errors = pct_errors.clip(-50, 50)
    ax4.hist(pct_errors, bins=50, edgecolor='black', alpha=0.7)
    ax4.axvline(x=0, color='r', linestyle='--')
    ax4.set_xlabel("Percentage Error (%)")
    ax4.set_ylabel("Frequency")
    ax4.set_title(f"MAPE = {metrics['mape']:.1f}% | Accuracy = {metrics['accuracy_percent']:.1f}%")

    plt.tight_layout()
    plt.savefig("model_evaluation_rf.png", dpi=150)
    plt.show()

    return fig

def plot_feature_importance(model, feature_columns):
    """Plot feature importance dari Random Forest"""
    if hasattr(model, 'feature_importances_'):
        importances = model.feature_importances_

        indices = np.argsort(importances)[::-1]

        plt.figure(figsize=(12, 8))
        plt.title("Random Forest Feature Importance")
        plt.bar(range(len(importances)), importances[indices])
        plt.xticks(range(len(importances)), [feature_columns[i] for i in indices], rotation=45, ha='right')
        plt.xlabel("Features")
        plt.ylabel("Importance")
        plt.tight_layout()
        plt.savefig("feature_importance_rf.png", dpi=150)
        plt.show()

        print("\n=== TOP 10 FEATURES (Random Forest) ===")
        for i in range(min(10, len(indices))):
            print(f"{i+1}. {feature_columns[indices[i]]}: {importances[indices[i]]:.4f}")

        return dict(zip(feature_columns, importances))
    return None

